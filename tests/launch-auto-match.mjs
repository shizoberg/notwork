import assert from 'node:assert/strict';
import { functionSandbox } from './helpers/function-sandbox.mjs';
process.env.NTW_AI_ENABLED = 'false';
const adminPassword = "local-recovery-test";
const sandbox = await functionSandbox({ adminPassword });
try {
  const registry = await sandbox.load('_event-registry-store');
  const datasets = await sandbox.load('_launch-datasets');
  const context = await sandbox.load('_event-product-context');
  const network = await sandbox.load('_event-network-store');
  const handler = (await sandbox.load('event-network')).default;
  const event = await registry.createEvent((await sandbox.loadLib('event-poll')).novemberEventDraft);
  await datasets.changeLaunchDataset(event, {action:'createDataset', name:'Isolated live test', mode:'live', activate:true});
  const call = async (input, extraHeaders = {}) => {
    const response = await handler(new Request('http://127.0.0.1/api/test', {method:'POST', headers:{'content-type':'application/json',origin:'http://127.0.0.1', ...extraHeaders}, body:JSON.stringify({event:event.slug,...input})}), {});
    const body = await response.text();
    assert.ok(response.ok, body);
    return JSON.parse(body);
  };
  const people = [];
  const register = async () => {
    const person = await call({action:'launchGuest',firstName:`Auto Person ${people.length}`,email:`auto-${people.length}@example.org`,jobTitle:'Designer',intro:'I build products with people',offers:['tasarım'],offersDetail:'Designing products',needs:'Meeting software developers',eventConsent:true});
    people.push(person); return person;
  };
  const match = person => call({action:'match',accessToken:person.accessToken});
  for(let i=0;i<19;i++) await register();
  assert.equal((await match(people[0])).waitingReason,'threshold');
  const state = () => context.runWithEventRequestContext(event.slug,'matchlab',()=>network.getMatchLaunchState(network.getEventNetworkStore()));
  assert.equal((await state()).status,'waiting');
  await register();
  assert.notEqual((await state()).status,'waiting');
  for(let i=0;i<5 && (await state()).status!=='open';i++) await Promise.all(people.map(match));
  assert.equal((await state()).status,'open');
  let results = await Promise.all(people.map(match));
  const original = new Map(results.filter(r=>r.group).map(r=>[r.registration.participant.id,r.group.id]));
  assert.equal(original.size,18);
  assert.equal(new Set(original.values()).size,6);
  await register();
  results = await Promise.all(people.map(match));
  assert.ok(results.every(r=>r.group));
  assert.equal(new Set(results.map(r=>r.group.id)).size,7);
  for(let i=21;i<200;i++) await register();
  results = await Promise.all(people.map(match));
  const groups = new Map(results.filter(r=>r.group).map(r=>[r.group.id,r.group]));
  assert.equal(groups.size,66);
  assert.equal(results.filter(r=>!r.group).length,2);
  const memberIds = [...groups.values()].flatMap(g=>g.members.map(m=>m.participantId));
  assert.equal(memberIds.length,198);
  assert.equal(new Set(memberIds).size,198,'No participant in multiple groups');
  for(const r of results) if(original.has(r.registration.participant.id)) assert.equal(r.group.id, original.get(r.registration.participant.id),'New arrivals preserve existing groups');
  const again = await Promise.all(people.map(match));
  assert.deepEqual(again.map(r=>r.group?.id),results.map(r=>r.group?.id),'Polling never reruns completed matches');
  const before = results[0];
  const edited = await call({action:'launchProfileUpdate', accessToken:people[0].accessToken,
    firstName:'Edited Participant', email:'edited@example.org', jobTitle:'New title', intro:'New introduction',
    offers:['teknoloji'], offersDetail:'New offer', needs:'New goal', aiAnalysisConsent:true, targetId:people[1].participant.id});
  assert.equal(edited.registration.participant.id,people[0].participant.id);
  assert.equal(edited.registration.participant.publicCode,people[0].participant.publicCode);
  assert.equal(edited.registration.accessToken,people[0].accessToken);
  const persisted = await call({action:'launchProfile',accessToken:people[0].accessToken});
  assert.equal(persisted.email,'edited@example.org');
  assert.equal(persisted.registration.intro,'New introduction');
  assert.equal(persisted.registration.jobTitle,'New title');
  assert.equal((await match(people[0])).group.id,before.group.id);
  const peer = await match(people.find(p=>p.participant.id===before.group.members.find(m=>m.participantId!==people[0].participant.id).participantId));
  assert.equal(peer.group.members.find(m=>m.participantId===people[0].participant.id).jobTitle,'New title');
  const other = await call({action:'launchProfile',accessToken:people[1].accessToken});
  assert.equal(other.registration.profile.firstName,'Auto');
  await assert.rejects(call({action:'launchProfileUpdate',accessToken:'invalid', firstName:'Intruder',jobTitle:'No'}));
  await assert.rejects(call({action:'launchProfileUpdate',accessToken:people[1].accessToken,firstName:'Other',jobTitle:'Title',email:'edited@example.org'}));
  const directory = await call({action:'people',accessToken:people[1].accessToken});
  assert.equal(directory.people.find(p=>p.id===people[0].participant.id).jobTitle,'New title');
  assert.ok(!JSON.stringify(directory).includes('edited@example.org'));
  const restored = await call({action:'launchDeviceResume', accessToken:people[0].accessToken, email:'edited@example.org'});
  assert.equal(restored.participant.id,people[0].participant.id);
  const cookieRestored = await call({action:'launchDeviceResume'}, {cookie:`launch_device=${people[0].accessToken}`});
  assert.equal(cookieRestored.participant.id,people[0].participant.id);
  const staleCookie = await call({action:'launchDeviceResume',accessToken:people[0].accessToken,email:'edited@example.org'}, {cookie:`launch_device=${people[1].accessToken}`});
  assert.equal(staleCookie.participant.id,people[0].participant.id);
  await assert.rejects(call({action:'launchDeviceResume',email:'edited@example.org'}));
  await assert.rejects(call({action:'launchDeviceResume',accessToken:people[0].accessToken,email:'wrong@example.org'}));
  assert.equal((await match(restored)).group.id,before.group.id);
  const admin = (await sandbox.load('event-network-admin')).default;
  const rescue = async (password) => admin(new Request('http://127.0.0.1/api/admin/test', {
    method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({action:'recoverParticipant',event:event.slug,password,participantId:people[0].participant.id})}), {});
  assert.equal((await rescue('wrong')).status,401);
  const rescueResponse = await rescue(adminPassword);
  assert.equal(rescueResponse.status,200);
  const rescueToken = (await rescueResponse.json()).path.split('sign-in=')[1];
  const rescuePerson = await call({action:'launchSignInComplete',accessToken:rescueToken});
  assert.equal(rescuePerson.participant.id,people[0].participant.id);
  assert.equal((await match(rescuePerson)).group.id,before.group.id);
  await assert.rejects(call({action:'launchSignInComplete',accessToken:rescueToken}));
  console.log('PASS admin recovery: authorized only, one use, preserved existing identity and match');
  console.log('PASS recovery: token backup, cookie backup, stale cookie fallback, same group; email alone cannot access another account');
  console.log('PASS profile: fields persist, own token only, duplicate email rejected, contact private, group/code/session preserved, peers see changes');
  console.log('PASS: first 20 auto-start, 200 arrivals, 66 stable trios + 2 waiting, concurrent retries preserve memberships');
} finally { await sandbox.cleanup(); }
