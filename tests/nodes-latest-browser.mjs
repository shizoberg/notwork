import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[],writes=[],failed=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(r.method()==='POST')writes.push(r.url())});
page.on('response',r=>{if(r.url().includes('/nodes-app/')&&r.status()>=400)failed.push(r.url())});
await page.addInitScript(()=>{try{localStorage.setItem('notwork-cookie-consent-v1',JSON.stringify({status:'necessary'}))}catch{}});
try{
 await page.goto(`${process.env.DEMO_TEST_URL||'http://127.0.0.1:5200'}/nodes`);
 const f=page.frameLocator('iframe');
 await f.locator('[data-ui="setup-start"]').click();
 await f.locator('#setup-name').fill('Demo Deniz');
 assert.equal(await f.locator('.setup-preview-person').count(),1);
 assert.equal(await f.locator('.setup-preview-person img').count(),0);
 await f.locator('#node-setup-form button.primary').click();
 assert.equal(await f.locator('.setup-preview-person').count(),2);
 for(let i=1;i<6;i++) await f.locator('[data-ui="setup-skip"]').click();
 await f.getByRole('button',{name:'Profil',exact:true}).click();
 await f.getByText('Demo Deniz',{exact:true}).first().waitFor();
 await f.getByRole('button',{name:'Nodes',exact:true}).click();
 await f.getByRole('button',{name:'Community',exact:true}).click();
 await f.locator('[data-ui="join-event"]').click();
 await f.getByRole('textbox',{name:'Etkinlik kodu',exact:true}).fill('NTW2026');
 await f.locator('#join-form button[type="submit"]').click();
 await f.locator('[data-roadmap="skip"]').click();
 await f.getByRole('button',{name:'Eşleşmeye başla',exact:true}).click();
 await f.getByRole('button',{name:'Grubumu bul',exact:true}).click();
 await f.getByRole('button',{name:'Bora',exact:true}).click();
 await f.getByText('Sol önünde',{exact:true}).waitFor();
 await page.screenshot({path:'/tmp/nodes-current-mobile.png',animations:'disabled'});
 const frame=page.frames().find(x=>x.url().includes('/nodes-app/'));
 assert.equal(await frame.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.reload();
 await f.getByRole('button',{name:'Örnek profille keşfet'}).click();
 await page.setViewportSize({width:1440,height:1000});
 await page.frames().find(x=>x.url().includes('/nodes-app/')).waitForFunction(()=>innerWidth===1440);
 await page.screenshot({path:'/tmp/nodes-current-desktop.png',animations:'disabled'});
 assert.deepEqual(errors,[]);assert.deepEqual(failed,[]);assert.deepEqual(writes,[]);
 console.log('PASS latest Nodes: six-step setup, colored nodes, profile, navigation, event code, match/finder, quick demo, mobile/desktop. No writes or missing assets.');
}finally{await browser.close()}
